fn derive_impl(input: &DeriveInput) -> syn::Result<TokenStream2> {
    let name = &input.ident;
    let type_name_str = parse_dds_typename(input).unwrap_or_else(|| name.to_string());
    let metadata_method = match parse_dds_type_metadata(input) {
        Some((info, map)) => quote! {
            fn type_metadata_blobs() -> Option<(&'static [u8], &'static [u8])> {
                Some((#info, #map))
            }
        },
        None => quote! {},
    };

    let fields = match &input.data {
        Data::Struct(data) => match &data.fields {
            Fields::Named(f) => &f.named,
            Fields::Unnamed(_) => {
                return Err(syn::Error::new_spanned(
                    &input.ident,
                    "DdsType only supports structs with named fields",
                ))
            }
            Fields::Unit => {
                return Err(syn::Error::new_spanned(
                    &input.ident,
                    "DdsType cannot be derived for unit structs",
                ))
            }
        },
        _ => {
            return Err(syn::Error::new_spanned(
                &input.ident,
                "DdsType can only be derived for structs",
            ))
        }
    };

    let mut main_ops_parts: Vec<TokenStream2> = Vec::new();
    let mut tail_block_parts: Vec<TokenStream2> = Vec::new();
    let mut key_steps: Vec<TokenStream2> = Vec::new();
    let mut post_key_steps: Vec<TokenStream2> = Vec::new();
    let mut clone_fields: Vec<TokenStream2> = Vec::new();
    let mut native_fields: Vec<TokenStream2> = Vec::new();
    let mut native_init_fields: Vec<TokenStream2> = Vec::new();
    let mut len_exprs: Vec<TokenStream2> = Vec::new();
    let mut key_count_exprs: Vec<TokenStream2> = Vec::new();
    let native_name = format_ident!("__CycloneDdsNative{}", name);

    for field in fields {
        let field_name = field.ident.as_ref().unwrap();
        let field_ty = &field.ty;
        let is_key = field.attrs.iter().any(|a| {
            a.path()
                .segments
                .last()
                .map(|s| s.ident == "key")
                .unwrap_or(false)
        });
        let is_enum = field.attrs.iter().any(|a| {
            a.path()
                .segments
                .last()
                .map(|s| s.ident == "dds_enum")
                .unwrap_or(false)
        });

        let offset_expr = quote! {
            ::std::mem::offset_of!(#native_name, #field_name) as u32
        };

        let primitive_type = field_typecode(field)?;
        let option_inner = option_inner_type(field_ty)?;
        let direct_string = is_direct_string(field_ty);
        let direct_vec = direct_vec_info(field_ty)?;
        let direct_vec_string = is_direct_vec_string(field_ty)?;
        let direct_vec_composite = direct_vec_composite_info(field_ty)?;
        let composite_seq = composite_sequence_type(field_ty)?;
        let composite_bounded_seq = composite_bounded_sequence_type(field_ty)?;
        // Which composite shape the ops chain below settled on, recorded once so
        // the native-layout chain does not have to re-derive it from the same
        // predicates in the same order. Two chains that must agree by
        // construction is the shape the width-table defect had.
        let mut native_kind = NativeKind::Plain;
        let nested_sequence = nested_sequence_info(field_ty, &offset_expr)?;
        let bounded_type = bounded_sequence_typecode(field_ty)?;
        let primitive_array = primitive_or_string_array_info(field_ty)?;
        let composite_arr = composite_array_type(field_ty)?;
        let enum_seq = if is_enum {
            enum_sequence_info(field_ty)?
        } else {
            None
        };
        let enum_bounded_seq = if is_enum {
            enum_bounded_sequence_info(field_ty)?
        } else {
            None
        };
        let enum_array = if is_enum {
            enum_array_info(field_ty)?
        } else {
            None
        };
        let enum_direct_vec = if is_enum {
            enum_direct_vec_info(field_ty)?
        } else {
            None
        };
        let is_composite_nested = primitive_type.is_none()
            && option_inner.is_none()
            && composite_seq.is_none()
            && composite_bounded_seq.is_none()
            && nested_sequence.is_none()
            && bounded_type.is_none()
            && direct_vec.is_none()
            && direct_vec_string.is_none()
            && direct_vec_composite.is_none()
            && !direct_string
            && primitive_array.is_none()
            && composite_arr.is_none()
            && enum_seq.is_none()
            && enum_bounded_seq.is_none()
            && enum_array.is_none()
            && enum_direct_vec.is_none()
            && !is_enum;

        let len_expr = if let Some(inner_ty) = option_inner.clone() {
            if is_key {
                return Err(syn::Error::new_spanned(
                    field,
                    "optional keyed fields are not supported yet",
                ));
            }
            if is_enum {
                main_ops_parts.push(quote! {
                    __ops.push(
                        cyclonedds::OP_ADR
                            | cyclonedds::OP_FLAG_OPT
                            | cyclonedds::OP_FLAG_EXT
                            | cyclonedds::TYPE_ENU
                            | <#inner_ty as cyclonedds::DdsEnumType>::enum_op_flags()
                    );
                    __ops.push(#offset_expr);
                    __ops.push(<#inner_ty as cyclonedds::DdsEnumType>::max_discriminant());
                });
                quote! { 3u32 }
            } else if is_direct_string(&inner_ty) {
                main_ops_parts.push(quote! {
                    __ops.push(cyclonedds::OP_ADR | cyclonedds::OP_FLAG_OPT | cyclonedds::OP_FLAG_EXT | cyclonedds::TYPE_STR);
                    __ops.push(#offset_expr);
                });
                quote! { 2u32 }
            } else if let Some((inner_typecode, word_count)) = field_typecode_from_type(&inner_ty)?
            {
                main_ops_parts.push(quote! {
                    __ops.push(cyclonedds::OP_ADR | cyclonedds::OP_FLAG_OPT | cyclonedds::OP_FLAG_EXT | #inner_typecode);
                    __ops.push(#offset_expr);
                });
                quote! { #word_count }
            } else {
                main_ops_parts.push(quote! {
                    // See the sibling TYPE_EXT emission below: the position is
                    // recorded here rather than recovered by scanning. The `0`
                    // width means "read it back off the opcode flags".
                    __patch_positions.push((__ops.len(), 2usize, 0u32));
                    __ops.push(cyclonedds::OP_ADR | cyclonedds::OP_FLAG_OPT | cyclonedds::OP_FLAG_EXT | cyclonedds::TYPE_EXT);
                    __ops.push(#offset_expr);
                    __ops.push(0u32);
                    __ops.push(<#inner_ty as cyclonedds::DdsType>::descriptor_size());
                });
                tail_block_parts.push(quote! {
                    __tail_blocks.push(<#inner_ty as cyclonedds::DdsType>::ops());
                });
                quote! { 4u32 }
            }
        } else if is_enum {
            if let Some(inner_ty) = enum_direct_vec.clone() {
                if is_key {
                    return Err(syn::Error::new_spanned(
                        field,
                        "keyed Vec<Enum> fields are not supported yet",
                    ));
                }
                main_ops_parts.push(quote! {
                    __ops.push(
                        cyclonedds::OP_ADR
                            | cyclonedds::TYPE_SEQ
                            | cyclonedds::SUBTYPE_ENU
                            | <#inner_ty as cyclonedds::DdsEnumType>::enum_op_flags()
                    );
                    __ops.push(#offset_expr);
                    __ops.push(<#inner_ty as cyclonedds::DdsEnumType>::max_discriminant());
                });
                quote! { 3u32 }
            } else if let Some(inner_ty) = enum_seq {
                if is_key {
                    return Err(syn::Error::new_spanned(
                        field,
                        "keyed sequence-of-enum fields are not supported yet",
                    ));
                }
                main_ops_parts.push(quote! {
                    __ops.push(
                        cyclonedds::OP_ADR
                            | cyclonedds::TYPE_SEQ
                            | cyclonedds::SUBTYPE_ENU
                            | <#inner_ty as cyclonedds::DdsEnumType>::enum_op_flags()
                    );
                    __ops.push(#offset_expr);
                    __ops.push(<#inner_ty as cyclonedds::DdsEnumType>::max_discriminant());
                });
                quote! { 3u32 }
            } else if let Some((inner_ty, bound_expr)) = enum_bounded_seq {
                if is_key {
                    return Err(syn::Error::new_spanned(
                        field,
                        "keyed bounded-sequence-of-enum fields are not supported yet",
                    ));
                }
                main_ops_parts.push(quote! {
                    __ops.push(
                        cyclonedds::OP_ADR
                            | cyclonedds::TYPE_BSQ
                            | cyclonedds::SUBTYPE_ENU
                            | <#inner_ty as cyclonedds::DdsEnumType>::enum_op_flags()
                    );
                    __ops.push(#offset_expr);
                    __ops.push(#bound_expr);
                    __ops.push(<#inner_ty as cyclonedds::DdsEnumType>::max_discriminant());
                });
                quote! { 4u32 }
            } else if let Some((len_expr_tokens, flags_expr, max_expr)) = enum_array {
                if is_key {
                    return Err(syn::Error::new_spanned(
                        field,
                        "keyed array-of-enum fields are not supported yet",
                    ));
                }
                main_ops_parts.push(quote! {
                    __ops.push(cyclonedds::OP_ADR | cyclonedds::TYPE_ARR | cyclonedds::SUBTYPE_ENU | #flags_expr);
                    __ops.push(#offset_expr);
                    __ops.push(#len_expr_tokens);
                    __ops.push(#max_expr);
                });
                quote! { 4u32 }
            } else if is_key {
                main_ops_parts.push(quote! {
                    __ops.push(cyclonedds::OP_ADR | cyclonedds::OP_FLAG_KEY | cyclonedds::TYPE_ENU | <#field_ty as cyclonedds::DdsEnumType>::enum_op_flags());
                    __ops.push(#offset_expr);
                    __ops.push(<#field_ty as cyclonedds::DdsEnumType>::max_discriminant());
                });
                quote! { 3u32 }
            } else {
                main_ops_parts.push(quote! {
                    __ops.push(cyclonedds::OP_ADR | cyclonedds::TYPE_ENU | <#field_ty as cyclonedds::DdsEnumType>::enum_op_flags());
                    __ops.push(#offset_expr);
                    __ops.push(<#field_ty as cyclonedds::DdsEnumType>::max_discriminant());
                });
                quote! { 3u32 }
            }
        } else if let Some((typecode_expr, word_count, _native_ty)) = direct_vec.clone() {
            main_ops_parts.push(quote! {
                __ops.push(cyclonedds::OP_ADR | #typecode_expr);
                __ops.push(#offset_expr);
            });
            quote! { #word_count }
        } else if let Some(inner_ty) = direct_vec_composite.clone() {
            main_ops_parts.push(quote! {
                __patch_positions.push((__ops.len(), 3usize, 4u32));
                __ops.push(cyclonedds::OP_ADR | cyclonedds::TYPE_SEQ | cyclonedds::SUBTYPE_STU);
                __ops.push(#offset_expr);
                __ops.push(<#inner_ty as cyclonedds::DdsType>::descriptor_size());
                __ops.push(0u32);
            });
            tail_block_parts.push(quote! {
                __tail_blocks.push(<#inner_ty as cyclonedds::DdsType>::ops());
            });
            quote! { 4u32 }
        } else if direct_vec_string.is_some() {
            main_ops_parts.push(quote! {
                __ops.push(cyclonedds::OP_ADR | cyclonedds::TYPE_SEQ | cyclonedds::SUBTYPE_STR);
                __ops.push(#offset_expr);
            });
            quote! { 2u32 }
        } else if direct_string {
            if is_key {
                main_ops_parts.push(quote! {
                    __ops.extend(cyclonedds::adr_key(cyclonedds::TYPE_STR, #offset_expr));
                });
            } else {
                main_ops_parts.push(quote! {
                    __ops.extend(cyclonedds::adr(cyclonedds::TYPE_STR, #offset_expr));
                });
            }
            quote! { 2u32 }
        } else if let Some((child_block, total_len)) = nested_sequence {
            if is_key {
                return Err(syn::Error::new_spanned(
                    field,
                    "keyed nested sequence fields are not supported yet",
                ));
            }
            main_ops_parts.push(child_block);
            total_len
        } else if let Some(inner_ty) = composite_seq {
            if is_key {
                return Err(syn::Error::new_spanned(
                    field,
                    "keyed sequence-of-struct fields are not supported yet",
                ));
            }
            native_kind = NativeKind::CompositeSeq(inner_ty.clone());
            main_ops_parts.push(quote! {
                __patch_positions.push((__ops.len(), 3usize, 4u32));
                __ops.push(cyclonedds::OP_ADR | cyclonedds::TYPE_SEQ | cyclonedds::SUBTYPE_STU);
                __ops.push(#offset_expr);
                __ops.push(<#inner_ty as cyclonedds::DdsType>::descriptor_size());
                __ops.push(0u32);
            });
            tail_block_parts.push(quote! {
                __tail_blocks.push(<#inner_ty as cyclonedds::DdsType>::ops());
            });
            quote! { 4u32 }
        } else if let Some((inner_ty, bound_expr)) = composite_bounded_seq {
            if is_key {
                return Err(syn::Error::new_spanned(
                    field,
                    "keyed bounded-sequence-of-struct fields are not supported yet",
                ));
            }
            native_kind = NativeKind::CompositeBoundedSeq(inner_ty.clone(), bound_expr.clone());
            main_ops_parts.push(quote! {
                __patch_positions.push((__ops.len(), 4usize, 5u32));
                __ops.push(cyclonedds::OP_ADR | cyclonedds::TYPE_BSQ | cyclonedds::SUBTYPE_STU);
                __ops.push(#offset_expr);
                __ops.push(#bound_expr);
                __ops.push(<#inner_ty as cyclonedds::DdsType>::descriptor_size());
                __ops.push(0u32);
            });
            tail_block_parts.push(quote! {
                __tail_blocks.push(<#inner_ty as cyclonedds::DdsType>::ops());
            });
            quote! { 5u32 }
        } else if let Some((typecode_expr, bound_expr)) = bounded_type {
            if is_key {
                main_ops_parts.push(quote! {
                    __ops.push(cyclonedds::OP_ADR | cyclonedds::OP_FLAG_KEY | #typecode_expr);
                    __ops.push(#offset_expr);
                    __ops.push(#bound_expr);
                });
            } else {
                main_ops_parts.push(quote! {
                    __ops.push(cyclonedds::OP_ADR | #typecode_expr);
                    __ops.push(#offset_expr);
                    __ops.push(#bound_expr);
                });
            }
            quote! { 3u32 }
        } else if let Some((typecode_expr, len_expr_tokens, extra_exprs, word_count)) =
            primitive_array
        {
            if is_key {
                return Err(syn::Error::new_spanned(
                    field,
                    "keyed primitive/string arrays are not supported yet",
                ));
            }
            main_ops_parts.push(quote! {
                __ops.push(cyclonedds::OP_ADR | #typecode_expr);
                __ops.push(#offset_expr);
                __ops.push(#len_expr_tokens);
                #(__ops.push(#extra_exprs);)*
            });
            quote! { #word_count }
        } else if let Some(inner_ty) = composite_arr {
            if is_key {
                return Err(syn::Error::new_spanned(
                    field,
                    "keyed array-of-struct fields are not supported yet",
                ));
            }
            let Type::Array(arr) = field_ty else {
                unreachable!()
            };
            let len_expr_tokens = &arr.len;
            native_kind = NativeKind::CompositeArray(inner_ty.clone());
            main_ops_parts.push(quote! {
                __patch_positions.push((__ops.len(), 3usize, 5u32));
                __ops.push(cyclonedds::OP_ADR | cyclonedds::TYPE_ARR | cyclonedds::SUBTYPE_STU);
                __ops.push(#offset_expr);
                __ops.push((#len_expr_tokens) as u32);
                __ops.push(0u32);
                __ops.push(<#inner_ty as cyclonedds::DdsType>::descriptor_size());
            });
            tail_block_parts.push(quote! {
                __tail_blocks.push(<#inner_ty as cyclonedds::DdsType>::ops());
            });
            quote! { 5u32 }
        } else if let Some((typecode_expr, word_count)) = primitive_type {
            if is_key {
                main_ops_parts.push(quote! {
                    __ops.extend(cyclonedds::adr_key(#typecode_expr, #offset_expr));
                });
            } else {
                main_ops_parts.push(quote! {
                    __ops.extend(cyclonedds::adr(#typecode_expr, #offset_expr));
                });
            }
            quote! { #word_count }
        } else {
            native_kind = NativeKind::CompositeNested;
            main_ops_parts.push(quote! {
                // Record where this TYPE_EXT lands so the patch step below can
                // find it without re-scanning the instruction stream.
                __patch_positions.push((__ops.len(), 2usize, 0u32));
                __ops.push(
                    cyclonedds::OP_ADR
                        | if <#field_ty as cyclonedds::DdsType>::key_count() > 0 {
                            cyclonedds::OP_FLAG_KEY
                        } else {
                            0
                        }
                        | cyclonedds::TYPE_EXT
                );
                __ops.push(#offset_expr);
                __ops.push(0);
            });
            tail_block_parts.push(quote! {
                __tail_blocks.push(<#field_ty as cyclonedds::DdsType>::ops());
            });
            quote! { 3u32 }
        };
        key_steps.push(if is_key {
            quote! {
                __keys.push(cyclonedds::KeyDescriptor { name: stringify!(#field_name).into(), ops_path: vec![__ops_index] });
            }
        } else if is_composite_nested
        {
            quote! {
                for __child_key in <#field_ty as cyclonedds::DdsType>::keys() {
                    let mut __ops_path = ::std::vec::Vec::with_capacity(1 + __child_key.ops_path.len());
                    __ops_path.push(__ops_index);
                    __ops_path.extend(__child_key.ops_path.iter().copied());
                    __keys.push(cyclonedds::KeyDescriptor {
                        name: format!("{}.{}", stringify!(#field_name), __child_key.name),
                        ops_path: __ops_path,
                    });
                }
            }
        } else {
            quote! {}
        });
        post_key_steps.push(if option_inner.is_some() {
            quote! {
                __post.push(cyclonedds::OP_MID | __ops_index);
                __post.push(__member_id);
                __member_id += 1;
            }
        } else {
            quote! {}
        });

        clone_fields.push(quote! {
            #field_name: ::std::clone::Clone::clone(&__raw.#field_name),
        });
        if let Some(inner_ty) = option_inner.as_ref() {
            native_fields.push(quote! { pub #field_name: *mut ::std::ffi::c_void, });
            native_init_fields.push(if is_enum {
                quote! {
                    #field_name: if let Some(value) = &self.#field_name {
                        arena.hold(::std::clone::Clone::clone(value)) as *const #inner_ty as *mut ::std::ffi::c_void
                    } else {
                        ::std::ptr::null_mut()
                    },
                }
            } else if is_direct_string(inner_ty) {
                quote! {
                    #field_name: if let Some(value) = &self.#field_name {
                        arena.hold(cyclonedds::DdsString::new(value)?) as *const cyclonedds::DdsString as *mut ::std::ffi::c_void
                    } else {
                        ::std::ptr::null_mut()
                    },
                }
            } else if field_typecode_from_type(inner_ty)?.is_some() {
                quote! {
                    #field_name: if let Some(value) = &self.#field_name {
                        arena.hold(::std::clone::Clone::clone(value)) as *const #inner_ty as *mut ::std::ffi::c_void
                    } else {
                        ::std::ptr::null_mut()
                    },
                }
            } else {
                quote! {
                    #field_name: if let Some(value) = &self.#field_name {
                        value.write_to_native(arena)? as *mut ::std::ffi::c_void
                    } else {
                        ::std::ptr::null_mut()
                    },
                }
            });
            clone_fields.pop();
            clone_fields.push(if is_enum {
                quote! {
                    #field_name: if __raw.#field_name.is_null() {
                        None
                    } else {
                        Some(::std::ptr::read(__raw.#field_name as *const #inner_ty))
                    },
                }
            } else if is_direct_string(inner_ty) {
                quote! {
                    #field_name: if __raw.#field_name.is_null() {
                        None
                    } else {
                        Some((*( __raw.#field_name as *const cyclonedds::DdsString)).to_string_lossy())
                    },
                }
            } else if field_typecode_from_type(inner_ty)?.is_some() {
                quote! {
                    #field_name: if __raw.#field_name.is_null() {
                        None
                    } else {
                        Some(::std::ptr::read(__raw.#field_name as *const #inner_ty))
                    },
                }
            } else {
                quote! {
                    #field_name: if __raw.#field_name.is_null() {
                        None
                    } else {
                        Some(<#inner_ty as cyclonedds::DdsType>::clone_out(__raw.#field_name as *const #inner_ty))
                    },
                }
            });
        } else if direct_string {
            native_fields.push(quote! { pub #field_name: cyclonedds::DdsString, });
            native_init_fields.push(quote! {
                #field_name: cyclonedds::DdsString::new(&self.#field_name)?,
            });
            clone_fields.pop();
            clone_fields.push(quote! {
                #field_name: __raw.#field_name.to_string_lossy(),
            });
        } else if let Some((_, _, native_ty)) = direct_vec.as_ref() {
            native_fields.push(quote! { pub #field_name: #native_ty, });
            native_init_fields.push(quote! {
                #field_name: <#native_ty>::from_slice(&self.#field_name)?,
            });
            clone_fields.pop();
            clone_fields.push(quote! {
                #field_name: __raw.#field_name.to_vec(),
            });
        } else if let Some(inner_ty) = direct_vec_composite.as_ref().filter(|_| !is_enum) {
            // `!is_enum` mirrors the ops chain, which gives `#[dds_enum]` first
            // refusal: `Vec<SomeEnum>` matches "vector of non-primitive" too, but
            // an enum is a scalar on the wire and has no native layout of its own.
            // The element type on the wire is the inner type's *native* layout.
            // Using `#inner_ty` here handed CycloneDDS a buffer of Rust values —
            // with a `String` where the ops array said `char *` — and a stride
            // that was too large by the difference between the two layouts.
            let native_ty =
                quote! { cyclonedds::DdsSequence<<#inner_ty as cyclonedds::DdsType>::Native> };
            native_fields.push(quote! { pub #field_name: #native_ty, });
            native_init_fields.push(quote! {
                #field_name: {
                    let mut __elems = ::std::vec::Vec::with_capacity(self.#field_name.len());
                    for __value in self.#field_name.iter() {
                        __elems.push(
                            <#inner_ty as cyclonedds::DdsNativeValue>::to_native_value(
                                __value, arena,
                            )?,
                        );
                    }
                    cyclonedds::DdsSequence::from_vec(__elems)?
                },
            });
            clone_fields.pop();
            clone_fields.push(quote! {
                #field_name: {
                    let mut __out = ::std::vec::Vec::with_capacity(__raw.#field_name.len());
                    for __element in __raw.#field_name.iter() {
                        __out.push(<#inner_ty as cyclonedds::DdsType>::clone_out(
                            __element as *const <#inner_ty as cyclonedds::DdsType>::Native
                                as *const #inner_ty,
                        )?);
                    }
                    __out
                },
            });
        } else if direct_vec_string.is_some() {
            native_fields
                .push(quote! { #field_name: cyclonedds::DdsSequence<cyclonedds::DdsString>, });
            native_init_fields.push(quote! {
                #field_name: {
                    let __converted: ::std::vec::Vec<cyclonedds::DdsString> = self
                        .#field_name
                        .iter()
                        .map(|value| cyclonedds::DdsString::new(value))
                        .collect::<cyclonedds::DdsResult<_>>()?;
                    cyclonedds::DdsSequence::<cyclonedds::DdsString>::from_slice(&__converted)?
                },
            });
            clone_fields.pop();
            clone_fields.push(quote! {
                #field_name: __raw
                    .#field_name
                    .to_vec()
                    .into_iter()
                    .map(|value| value.to_string_lossy())
                    .collect(),
            });
        } else if let Some(inner_ty) = enum_direct_vec.as_ref() {
            let native_ty = quote! { cyclonedds::DdsSequence<#inner_ty> };
            native_fields.push(quote! { pub #field_name: #native_ty, });
            native_init_fields.push(quote! {
                #field_name: <#native_ty>::from_slice(&self.#field_name)?,
            });
            clone_fields.pop();
            clone_fields.push(quote! {
                #field_name: __raw.#field_name.to_vec(),
            });
        } else if let NativeKind::CompositeSeq(inner_ty) = &native_kind {
            // `DdsSequence<Inner>` declared directly by the user: same
            // translation as `Vec<Inner>`, the element type on the wire is
            // `Inner::Native`.
            native_fields.push(quote! {
                pub #field_name:
                    cyclonedds::DdsSequence<<#inner_ty as cyclonedds::DdsType>::Native>,
            });
            native_init_fields.push(quote! {
                #field_name: {
                    let mut __elems = ::std::vec::Vec::with_capacity(self.#field_name.len());
                    for __value in self.#field_name.iter() {
                        __elems.push(
                            <#inner_ty as cyclonedds::DdsNativeValue>::to_native_value(
                                __value, arena,
                            )?,
                        );
                    }
                    cyclonedds::DdsSequence::from_vec(__elems)?
                },
            });
            clone_fields.pop();
            clone_fields.push(quote! {
                #field_name: {
                    let mut __out = ::std::vec::Vec::with_capacity(__raw.#field_name.len());
                    for __element in __raw.#field_name.iter() {
                        __out.push(<#inner_ty as cyclonedds::DdsType>::clone_out(
                            __element as *const <#inner_ty as cyclonedds::DdsType>::Native
                                as *const #inner_ty,
                        )?);
                    }
                    cyclonedds::DdsSequence::from_vec(__out)?
                },
            });
        } else if let NativeKind::CompositeBoundedSeq(inner_ty, bound_expr) = &native_kind {
            native_fields.push(quote! {
                pub #field_name: cyclonedds::DdsBoundedSequence<
                    <#inner_ty as cyclonedds::DdsType>::Native,
                    { #bound_expr as usize },
                >,
            });
            native_init_fields.push(quote! {
                #field_name: {
                    let mut __elems = ::std::vec::Vec::with_capacity(self.#field_name.len());
                    for __value in self.#field_name.iter() {
                        __elems.push(
                            <#inner_ty as cyclonedds::DdsNativeValue>::to_native_value(
                                __value, arena,
                            )?,
                        );
                    }
                    cyclonedds::DdsBoundedSequence::from_vec(__elems)?
                },
            });
            clone_fields.pop();
            clone_fields.push(quote! {
                #field_name: {
                    let mut __out = ::std::vec::Vec::with_capacity(__raw.#field_name.len());
                    for __element in __raw.#field_name.iter() {
                        __out.push(<#inner_ty as cyclonedds::DdsType>::clone_out(
                            __element as *const <#inner_ty as cyclonedds::DdsType>::Native
                                as *const #inner_ty,
                        )?);
                    }
                    cyclonedds::DdsBoundedSequence::from_vec(__out)?
                },
            });
        } else if let NativeKind::CompositeArray(inner_ty) = &native_kind {
            let Type::Array(arr) = field_ty else {
                unreachable!()
            };
            let arr_len = &arr.len;
            native_fields.push(quote! {
                pub #field_name: [<#inner_ty as cyclonedds::DdsType>::Native; #arr_len],
            });
            native_init_fields.push(quote! {
                #field_name: {
                    let mut __elems = ::std::vec::Vec::with_capacity(#arr_len);
                    for __value in self.#field_name.iter() {
                        __elems.push(
                            <#inner_ty as cyclonedds::DdsNativeValue>::to_native_value(
                                __value, arena,
                            )?,
                        );
                    }
                    // Length is `#arr_len` by construction; `map_err` avoids
                    // requiring `Debug` on the native element type.
                    match <::std::vec::Vec<_> as ::std::convert::TryInto<
                        [<#inner_ty as cyclonedds::DdsType>::Native; #arr_len],
                    >>::try_into(__elems)
                    {
                        Ok(__array) => __array,
                        Err(_) => return Err(cyclonedds::DdsError::BadParameter(
                            concat!(
                                "array length mismatch converting field `",
                                stringify!(#field_name),
                                "` to its native layout",
                            )
                            .into(),
                        )),
                    }
                },
            });
            clone_fields.pop();
            clone_fields.push(quote! {
                #field_name: {
                    let mut __out = ::std::vec::Vec::with_capacity(#arr_len);
                    for __element in __raw.#field_name.iter() {
                        __out.push(<#inner_ty as cyclonedds::DdsType>::clone_out(
                            __element as *const <#inner_ty as cyclonedds::DdsType>::Native
                                as *const #inner_ty,
                        )?);
                    }
                    match <::std::vec::Vec<_> as ::std::convert::TryInto<
                        [#inner_ty; #arr_len],
                    >>::try_into(__out)
                    {
                        Ok(__array) => __array,
                        Err(_) => return Err(cyclonedds::DdsError::BadParameter(
                            concat!(
                                "array length mismatch reading field `",
                                stringify!(#field_name),
                                "` from its native layout",
                            )
                            .into(),
                        )),
                    }
                },
            });
        } else if matches!(native_kind, NativeKind::CompositeNested) {
            // A nested struct/union member. Its sub-ops address the field
            // through `Inner::Native`, so the enclosing native struct has to
            // hold that layout too — keeping `#field_ty` here made the outer
            // offsets and the inner ops describe two different structs.
            native_fields.push(quote! {
                pub #field_name: <#field_ty as cyclonedds::DdsType>::Native,
            });
            native_init_fields.push(quote! {
                #field_name: <#field_ty as cyclonedds::DdsNativeValue>::to_native_value(
                    &self.#field_name,
                    arena,
                )?,
            });
            clone_fields.pop();
            clone_fields.push(quote! {
                #field_name: <#field_ty as cyclonedds::DdsType>::clone_out(
                    &__raw.#field_name as *const <#field_ty as cyclonedds::DdsType>::Native
                        as *const #field_ty,
                )?,
            });
        } else {
            native_fields.push(quote! { pub #field_name: #field_ty, });
            native_init_fields.push(quote! {
                #field_name: ::std::clone::Clone::clone(&self.#field_name),
            });
        }
        len_exprs.push(len_expr);
        key_count_exprs.push(if is_key {
            quote! { 1usize }
        } else if is_composite_nested {
            quote! { <#field_ty as cyclonedds::DdsType>::key_count() }
        } else {
            quote! { 0usize }
        });
    }

    let native_struct = quote! {
        #[repr(C)]
        pub struct #native_name {
            #(#native_fields)*
        }
    };

    let descriptor_methods = quote! {
        fn write_to_native<'a>(
            &'a self,
            arena: &'a mut cyclonedds::write_arena::WriteArena,
        ) -> cyclonedds::DdsResult<*const ::std::ffi::c_void> {
            let native =
                <Self as cyclonedds::DdsNativeValue>::to_native_value(self, arena)?;
            Ok(arena.hold(native) as *const #native_name as *const ::std::ffi::c_void)
        }
    };

    // Emitted for every type, not just the ones that need an arena write: a
    // composite used as another type's element has to be convertible to its
    // native layout even when it is POD itself.
    let native_value_impl = quote! {
        impl cyclonedds::DdsNativeValue for #name {
            #[allow(unused_variables)]
            fn to_native_value(
                &self,
                arena: &mut cyclonedds::write_arena::WriteArena,
            ) -> cyclonedds::DdsResult<#native_name> {
                Ok(#native_name {
                    #(#native_init_fields)*
                })
            }
        }
    };

    let clone_ptr = quote! {
        let __raw = &*(ptr as *const #native_name);
    };

    let expanded = quote! {
        #native_struct

        #native_value_impl

        unsafe impl cyclonedds::DdsType for #name {
            type Native = #native_name;

            fn type_name() -> &'static str { #type_name_str }

            fn descriptor_size() -> u32 {
                ::std::mem::size_of::<#native_name>() as u32
            }

            fn descriptor_align() -> u32 {
                ::std::mem::align_of::<#native_name>() as u32
            }

            fn ops() -> ::std::vec::Vec<u32> {
                let mut __ops = ::std::vec::Vec::new();
                let mut __tail_blocks: ::std::vec::Vec<::std::vec::Vec<u32>> = ::std::vec::Vec::new();
                // Filled in by the field emitters as they push each
                // ADR|TYPE_EXT instruction. This replaces a scanner that
                // re-walked the finished instruction stream trying to recover
                // those positions, which required a table of per-instruction
                // widths that has to stay in lockstep with dds_opcodes.h — ten
                // of its entries did not, and it only worked because a skipped
                // data word rarely looks like an opcode. The emitter already
                // knows where it put them, so nothing needs to be inferred.
                // (instruction start, index of the jump word within it, width of
                // the instruction). A width of 0 means "read it back off the
                // opcode flags", which only TYPE_EXT needs — it is 3 words
                // normally and 4 when OP_FLAG_EXT/OP_FLAG_OPT is set.
                #[allow(unused_mut)]
                let mut __patch_positions: ::std::vec::Vec<(usize, usize, u32)> =
                    ::std::vec::Vec::new();
                #(#main_ops_parts)*
                #(#tail_block_parts)*
                __ops.push(cyclonedds::OP_RTS);
                let mut __tail_index = 0usize;
                for (__insn_start, __jump_word, __insn_words) in __patch_positions {
                    let __child_start = __ops.len() as u32;
                    let __next_insn_words = if __insn_words != 0 {
                        __insn_words
                    } else {
                        let __op = __ops[__insn_start];
                        if (__op & (cyclonedds::OP_FLAG_EXT | cyclonedds::OP_FLAG_OPT)) != 0 {
                            4u32
                        } else {
                            3u32
                        }
                    };
                    // High half: where the *next member* instruction is, relative
                    // to this one — i.e. this instruction's width, because the
                    // child block lives after the terminating RTS rather than
                    // inline. Low half: where the child block starts. Emitting
                    // the child inline made the high half point at an RTS, so
                    // every member declared after a composite one was skipped.
                    __ops[__insn_start + __jump_word] =
                        (__next_insn_words << 16) + (__child_start - (__insn_start as u32));
                    let __child_ops = __tail_blocks[__tail_index].clone();
                    __ops.extend(__child_ops);
                    __tail_index += 1;
                }
                __ops
            }

            unsafe fn clone_out(ptr: *const Self) -> cyclonedds::DdsResult<Self> {
                #clone_ptr
                Ok(Self {
                    #(#clone_fields)*
                })
            }

            #descriptor_methods

            #metadata_method

            fn key_count() -> usize { 0usize #(+ #key_count_exprs)* }

            fn keys() -> ::std::vec::Vec<cyclonedds::KeyDescriptor> {
                let mut __keys = ::std::vec::Vec::new();
                let mut __ops_index = 0u32;
                #(
                    #key_steps
                    __ops_index += #len_exprs;
                )*
                __keys
            }

            fn post_key_ops() -> ::std::vec::Vec<u32> {
                let mut __post = ::std::vec::Vec::new();
                let mut __ops_index = 0u32;
                let mut __member_id = 1u32;
                #(
                    #post_key_steps
                    __ops_index += #len_exprs;
                )*
                if !__post.is_empty() {
                    __post.push(cyclonedds::OP_RTS);
                }
                __post
            }
        }
    };

    Ok(expanded)
}

fn derive_enum_impl(input: &DeriveInput) -> syn::Result<TokenStream2> {
    let name = &input.ident;
    let has_repr_i32 = input.attrs.iter().any(|attr| {
        if !attr.path().is_ident("repr") {
            return false;
        }
        let mut found = false;
        let _ = attr.parse_nested_meta(|meta| {
            found |= meta.path.is_ident("i32");
            Ok(())
        });
        found
    });
    if !has_repr_i32 {
        return Err(syn::Error::new_spanned(
            &input.ident,
            "DdsEnum requires #[repr(i32)]",
        ));
    }
    let data = match &input.data {
        Data::Enum(data) => data,
        _ => {
            return Err(syn::Error::new_spanned(
                &input.ident,
                "DdsEnum can only be derived for enums",
            ))
        }
    };

    let mut next_value: i64 = 0;
    let mut max_value: u32 = 0;
    for variant in &data.variants {
        if !matches!(variant.fields, Fields::Unit) {
            return Err(syn::Error::new_spanned(
                variant,
                "DdsEnum only supports fieldless enums",
            ));
        }

        let value = if let Some((_, expr)) = &variant.discriminant {
            parse_int_literal(expr)?
        } else {
            next_value
        };
        if value != next_value {
            return Err(syn::Error::new_spanned(
                variant,
                "DdsEnum discriminants must be contiguous from zero",
            ));
        }
        max_value = max_value.max(value as u32);
        next_value = value + 1;
    }

    Ok(quote! {
        impl cyclonedds::DdsEnumType for #name {
            fn max_discriminant() -> u32 {
                #max_value
            }
        }
    })
}

