/// Supported discriminant types and their CycloneDDS typecodes.
fn discriminant_info(ty: &Type) -> Option<(TokenStream2, u32)> {
    let s = type_to_string(ty);
    match s.as_str() {
        "bool" => Some((quote! { cyclonedds::TYPE_1BY }, 1)),
        "u8" => Some((quote! { cyclonedds::TYPE_1BY }, 1)),
        "i8" => Some((quote! { cyclonedds::TYPE_1BY | cyclonedds::OP_FLAG_SGN }, 1)),
        "u16" => Some((quote! { cyclonedds::TYPE_2BY }, 2)),
        "i16" => Some((quote! { cyclonedds::TYPE_2BY | cyclonedds::OP_FLAG_SGN }, 2)),
        "u32" => Some((quote! { cyclonedds::TYPE_4BY }, 4)),
        "i32" => Some((quote! { cyclonedds::TYPE_4BY | cyclonedds::OP_FLAG_SGN }, 4)),
        "u64" => Some((quote! { cyclonedds::TYPE_8BY }, 8)),
        "i64" => Some((quote! { cyclonedds::TYPE_8BY | cyclonedds::OP_FLAG_SGN }, 8)),
        _ => None,
    }
}

/// The discriminator's typecode for a `TYPE_UNI` header.
///
/// `dds_opcodes.h` spells the header as `[ADR, UNI, d, z] [offset] [alen]
/// [next-insn, cases]`: `d` is the discriminant type and it sits in the
/// **subtype** field, beside `TYPE_UNI` in the primary one. Emitting it as
/// another primary type OR'd `TYPE_UNI` (0x09) with `TYPE_4BY` (0x02) into an
/// opcode reading 0x0B, which is not a union at all.
///
/// The same paragraph restricts `d` to `{1BY, 2BY, 4BY, BLN}` — a 64-bit
/// discriminator has no encoding, so it is rejected rather than emitted wrong.
fn discriminant_subtype(ty: &Type) -> Option<TokenStream2> {
    let s = type_to_string(ty);
    match s.as_str() {
        "bool" | "u8" => Some(quote! { cyclonedds::SUBTYPE_1BY }),
        "i8" => Some(quote! { cyclonedds::SUBTYPE_1BY | cyclonedds::OP_FLAG_SGN }),
        "u16" => Some(quote! { cyclonedds::SUBTYPE_2BY }),
        "i16" => Some(quote! { cyclonedds::SUBTYPE_2BY | cyclonedds::OP_FLAG_SGN }),
        "u32" => Some(quote! { cyclonedds::SUBTYPE_4BY }),
        "i32" => Some(quote! { cyclonedds::SUBTYPE_4BY | cyclonedds::OP_FLAG_SGN }),
        _ => None,
    }
}

/// Return the primitive typecode for a union case member type, or None if it
/// is a composite (struct implementing DdsType) or String.
fn case_member_typecode(ty: &Type) -> Option<TokenStream2> {
    let s = type_to_string(ty);
    match s.as_str() {
        "i8" => Some(quote! { cyclonedds::TYPE_1BY | cyclonedds::OP_FLAG_SGN }),
        "u8" => Some(quote! { cyclonedds::TYPE_1BY }),
        "i16" => Some(quote! { cyclonedds::TYPE_2BY | cyclonedds::OP_FLAG_SGN }),
        "u16" => Some(quote! { cyclonedds::TYPE_2BY }),
        "i32" => Some(quote! { cyclonedds::TYPE_4BY | cyclonedds::OP_FLAG_SGN }),
        "u32" => Some(quote! { cyclonedds::TYPE_4BY }),
        "i64" => Some(quote! { cyclonedds::TYPE_8BY | cyclonedds::OP_FLAG_SGN }),
        "u64" => Some(quote! { cyclonedds::TYPE_8BY }),
        "f32" => Some(quote! { cyclonedds::TYPE_4BY | cyclonedds::OP_FLAG_FP }),
        "f64" => Some(quote! { cyclonedds::TYPE_8BY | cyclonedds::OP_FLAG_FP }),
        "bool" => Some(quote! { cyclonedds::TYPE_1BY }),
        _ => None,
    }
}

fn derive_union_impl(input: &DeriveInput) -> syn::Result<TokenStream2> {
    let name = &input.ident;
    let type_name_str = name.to_string();
    let native_name = format_ident!("__CycloneDdsNative{}", name);
    let native_value_name = format_ident!("__CycloneDdsNative{}Value", name);

    let data = match &input.data {
        Data::Enum(data) => data,
        _ => {
            return Err(syn::Error::new_spanned(
                &input.ident,
                "DdsUnion can only be derived for enums",
            ))
        }
    };

    // Parse #[dds_discriminant(Type)]
    let disc_ty: Type = input
        .attrs
        .iter()
        .find(|a| {
            a.path()
                .segments
                .last()
                .map(|s| s.ident == "dds_discriminant")
                .unwrap_or(false)
        })
        .ok_or_else(|| {
            syn::Error::new_spanned(
                &input.ident,
                "DdsUnion requires #[dds_discriminant(Type)] attribute",
            )
        })?
        .parse_args()?;

    let (_disc_typecode, _disc_size) = discriminant_info(&disc_ty).ok_or_else(|| {
        syn::Error::new_spanned(
            &disc_ty,
            "unsupported discriminant type; expected bool, u8, i8, u16, i16, u32, i32, u64, or i64",
        )
    })?;

    // Parse variants
    let mut cases: Vec<(
        /*value*/ i64,
        /*variant ident*/ syn::Ident,
        /*field type*/ Type,
        /*is_default*/ bool,
    )> = Vec::new();
    let mut default_variant_idx: Option<usize> = None;

    for (i, variant) in data.variants.iter().enumerate() {
        let is_default = variant.attrs.iter().any(|a| {
            a.path()
                .segments
                .last()
                .map(|s| s.ident == "dds_default")
                .unwrap_or(false)
        });

        let case_value = if is_default {
            // default case does not need a value; we use a sentinel
            -1i64
        } else {
            let case_attr = variant
                .attrs
                .iter()
                .find(|a| {
                    a.path()
                        .segments
                        .last()
                        .map(|s| s.ident == "dds_case")
                        .unwrap_or(false)
                })
                .ok_or_else(|| {
                    syn::Error::new_spanned(
                        variant,
                        "DdsUnion variant must have #[dds_case(N)] or #[dds_default]",
                    )
                })?;

            let expr: Expr = case_attr.parse_args()?;
            parse_int_literal(&expr)?
        };

        // Each variant must have exactly one unnamed field (newtype)
        let field_ty = match &variant.fields {
            Fields::Unnamed(fields) if fields.unnamed.len() == 1 => {
                fields.unnamed.first().unwrap().ty.clone()
            }
            _ => {
                return Err(syn::Error::new_spanned(
                    variant,
                    "DdsUnion variant must have exactly one unnamed field, e.g. IntValue(i32)",
                ))
            }
        };

        if is_default {
            if default_variant_idx.is_some() {
                return Err(syn::Error::new_spanned(
                    variant,
                    "DdsUnion can have at most one #[dds_default] variant",
                ));
            }
            default_variant_idx = Some(i);
        }

        cases.push((case_value, variant.ident.clone(), field_ty, is_default));
    }

    if cases.is_empty() {
        return Err(syn::Error::new_spanned(
            &input.ident,
            "DdsUnion enum must have at least one variant",
        ));
    }

    let n_cases = cases.len();
    let has_default = default_variant_idx.is_some();

    // Generate native union fields
    let union_arm_names: Vec<syn::Ident> = cases
        .iter()
        .map(|(_, ident, _, _)| format_ident!("{}_arm", ident.to_string().to_lowercase()))
        .collect();
    let union_arm_types: Vec<&Type> = cases.iter().map(|(_, _, ty, _)| ty).collect();

    // Build ops
    // Layout:
    //   ADR|TYPE_UNI, offset_of_disc, disc_offset(0), (n_cases<<16)|default_jump
    //   JEQ4|case_val_0, jump_to_case_0_ops
    //   JEQ4|case_val_1, jump_to_case_1_ops
    //   ...
    //   [default case ops]   // if has default
    //   [case 0 ops]         // inline ops for case 0 member
    //   [case 1 ops]         // inline ops for case 1 member
    //   ...
    //   RTS
    //
    // The header occupies 4 words.
    // Each JEQ4 occupies 2 words.
    // So the first case ops start at index = 4 + 2*n_cases.
    //
    // We need to compute the jump offsets.
    // For the default case: it comes right after JEQ4 entries.
    // For each numbered case i: it comes after default ops (if any) + all previous case ops.

    // Determine the native representation for each case member
    // Primitives: direct
    // String: uses DdsString (pointer, 8 bytes on 64-bit)
    // Struct (DdsType): uses the struct type directly

    // For each case, compute:
    //   - whether it needs an arena-based write (String/composite)
    //   - the ops words for the case member
    //   - the clone_out logic
    //   - the write_to_native logic

    let variant_idents: Vec<&syn::Ident> = cases.iter().map(|(_, ident, _, _)| ident).collect();
    let case_values: Vec<i64> = cases.iter().map(|(v, _, _, _)| *v).collect();

    // The value `clone_out` reports for a sample that took the default arm: any
    // value outside the declared set, so round-tripping it cannot be mistaken
    // for a declared case.
    let default_sentinel = if has_default {
        let max_case = case_values
            .iter()
            .filter(|v| **v >= 0)
            .max()
            .map(|v| *v as u32)
            .unwrap_or(0);
        let sentinel = max_case + 1;
        quote! { #sentinel }
    } else {
        quote! { 0u32 }
    };

    // Composite case members are still unsupported: a case whose member is a
    // struct needs its own sub-ops block, which the JEQ4 label format reaches
    // through a `[JEQ4, e | STU, i]` variant this derive does not emit yet.
    let has_composite = cases
        .iter()
        .any(|(_, _, ty, _)| !is_direct_string(ty) && case_member_typecode(ty).is_none());

    if has_composite {
        return Err(syn::Error::new_spanned(
            &input.ident,
            "DdsUnion supports primitive and String case members; composite (struct)              members are not implemented",
        ));
    }

    // Generate the clone_out native reading: read discriminator, then read the correct union arm
    let clone_out_arms: Vec<TokenStream2> = cases.iter().enumerate().map(|(i, (_, _, _, is_default))| {
        let variant = &variant_idents[i];
        let arm_name = &union_arm_names[i];
        let is_string = is_direct_string(&cases[i].2);
        if *is_default {
            if is_string {
                quote! { _ => ::std::result::Result::Ok(#name::#variant(__native.__value.#arm_name.to_string_lossy())), }
            } else {
                quote! { _ => ::std::result::Result::Ok(#name::#variant(::std::ptr::read(&__native.__value.#arm_name))), }
            }
        } else {
            let val = case_values[i] as u32;
            if is_string {
                quote! { #val => ::std::result::Result::Ok(#name::#variant(__native.__value.#arm_name.to_string_lossy())), }
            } else {
                quote! { #val => ::std::result::Result::Ok(#name::#variant(::std::ptr::read(&__native.__value.#arm_name))), }
            }
        }
    }).collect();

    // Generate write_to_native arms
    let write_arms: Vec<TokenStream2> = cases
        .iter()
        .enumerate()
        .map(|(i, (_, _, _, is_default))| {
            let variant = &variant_idents[i];
            let arm_name = &union_arm_names[i];
            let is_string = is_direct_string(&cases[i].2);

            // Pick the conversion at macro-expansion time. This used to emit a
            // runtime `if #is_string { DdsString::new(value)? } else {
            // Clone::clone(value) }`, interpolating the flag as a `true`/`false`
            // literal into a real `if`. Both branches then had to typecheck for
            // every case, so `DdsUnionDerive` demanded `i32: AsRef<str>` and
            // failed on the mismatched branch types -- it could not compile for
            // any non-String case at all. Nothing in the repository derived a
            // union, so nothing caught it, while the README advertised support.
            let assign = if is_string {
                quote! { cyclonedds::DdsString::new(value)? }
            } else {
                quote! { ::std::clone::Clone::clone(value) }
            };

            if *is_default {
                quote! {
                    #name::#variant(ref value) => {
                        __native.__disc = __disc_default_sentinel as #disc_ty;
                        __native.__value.#arm_name = #assign;
                    }
                }
            } else {
                let val = case_values[i] as u32;
                quote! {
                    #name::#variant(ref value) => {
                        __native.__disc = #val as #disc_ty;
                        __native.__value.#arm_name = #assign;
                    }
                }
            }
        })
        .collect();

    let n_cases_literal = n_cases as u32;

    // `[ADR, UNI, d, z] [offset] [alen] [next-insn, cases]`. `alen` is the number
    // of case labels, and the last word packs the distance to the next member
    // instruction (the whole block: 4 header words + 4 per label) in its high
    // half and the distance to the first label (always 4) in its low half.
    //
    // What was here before packed `(n_cases << 16) | default_target`, which is
    // neither field: `alen` was written as 0 and the high half held the case
    // count. Together with the JEQ4 rewrite below this is why a union had never
    // survived a round trip.
    let union_block_len = 4u32 + 4u32 * (n_cases as u32);
    let union_header_word3 = quote! { (#union_block_len << 16) + 4u32 };

    // The discriminator's type belongs in the subtype field; `disc_typecode`
    // returned a primary typecode and got OR'd into `TYPE_UNI`.
    let disc_subtype = discriminant_subtype(&disc_ty).ok_or_else(|| {
        syn::Error::new_spanned(
            &disc_ty,
            "unsupported discriminant type for a DDS union; CycloneDDS encodes the              discriminant in the subtype field, which admits only bool, u8, i8, u16,              i16, u32 and i32 (see dds_opcodes.h: \"d = discriminant type of              {1BY,2BY,4BY,BLN}\")",
        )
    })?;
    let union_default_flag = if has_default {
        quote! { | cyclonedds::OP_FLAG_DEF }
    } else {
        quote! {}
    };

    // Case labels in JEQ4 format: `[JEQ4, e | nBY, 0] [disc] [offset] 0`. Four
    // words, the member's type in the opcode and the member's offset in the
    // third word. The previous emitter wrote `[JEQ4] [disc] [0] [jump]` — no
    // member type, so the interpreter could not tell how to read the case, and
    // no offset, so it had nowhere to read it from. The jump it wrote instead
    // was computed as if each label were two words while four were emitted, so
    // it pointed four words short of its own case ops.
    //
    // Non-default labels keep declaration order; the default goes last with a
    // zero label value, which is what OP_FLAG_DEF on the header selects.
    let mut jeq4_order: Vec<usize> = (0..n_cases).filter(|i| !cases[*i].3).collect();
    if let Some(di) = default_variant_idx {
        jeq4_order.push(di);
    }
    let jeq4_entries: Vec<TokenStream2> = jeq4_order
        .iter()
        .map(|&i| {
            let (val, _, field_ty, is_default) = &cases[i];
            let label = if *is_default { 0u32 } else { *val as u32 };
            let member_type = if is_direct_string(field_ty) {
                quote! { cyclonedds::TYPE_STR }
            } else {
                let tc = case_member_typecode(field_ty).expect("checked above");
                // The label carries the bare typecode: idlc emits
                // `JEQ4 | DDS_OP_TYPE_8BY` for a `double`, with no FP flag.
                quote! { ((#tc) & cyclonedds::DDS_OP_TYPE_MASK_CONST) }
            };
            quote! {
                __ops.push(cyclonedds::OP_JEQ4 | #member_type);
                __ops.push(#label);
                // Every arm of the value union starts where the union does.
                __ops.push(::std::mem::offset_of!(#native_name, __value) as u32);
                __ops.push(0u32);
            }
        })
        .collect();

    let expanded = quote! {
        #[repr(C)]
        pub struct #native_name {
            __disc: #disc_ty,
            __value: #native_value_name,
        }

        #[repr(C)]
        pub union #native_value_name {
            #(
                #union_arm_names: #union_arm_types,
            )*
        }

        impl Default for #native_value_name {
            fn default() -> Self {
                // Unions can only have one field initialized; zero the first arm.
                unsafe { ::std::mem::zeroed() }
            }
        }

        unsafe impl cyclonedds::DdsType for #name {
            type Native = #native_name;

            fn type_name() -> &'static str { #type_name_str }

            fn ops() -> ::std::vec::Vec<u32> {
                let mut __ops = ::std::vec::Vec::new();
                // [ADR, UNI, d, z] [offset] [alen] [next-insn, cases]
                __ops.push(
                    cyclonedds::OP_ADR
                        | cyclonedds::OP_FLAG_MU
                        | cyclonedds::TYPE_UNI
                        | #disc_subtype
                        #union_default_flag
                );
                __ops.push(::std::mem::offset_of!(#native_name, __disc) as u32);
                __ops.push(#n_cases_literal);
                __ops.push(#union_header_word3);
                // alen case labels, in JEQ4 format
                #(#jeq4_entries)*
                __ops.push(cyclonedds::OP_RTS);
                __ops
            }

            fn descriptor_size() -> u32 {
                ::std::mem::size_of::<#native_name>() as u32
            }

            fn descriptor_align() -> u32 {
                ::std::mem::align_of::<#native_name>() as u32
            }

            unsafe fn clone_out(ptr: *const Self) -> cyclonedds::DdsResult<Self> {
                let __native = &*(ptr as *const #native_name);
                let __disc = __native.__disc as u32;
                match __disc {
                    #(#clone_out_arms)*
                    // Only reachable for unions declared without a
                    // `#[dds_default]` variant. The discriminator arrives from
                    // the network, so this is remote input: a peer built from a
                    // different revision of the IDL is enough to produce one.
                    //
                    // Fabricating a variant is not an option — reading a union
                    // arm that is not the active one dereferences garbage for
                    // any arm holding a string or sequence. This used to
                    // `panic!`, which the `catch_unwind` barriers contained at
                    // the FFI boundary but which still unwound on the caller's
                    // own thread from `read`/`take`. It is an error now, so the
                    // sample is discarded and the call returns normally.
                    //
                    // Declaring a `#[dds_default]` variant avoids this path
                    // entirely and remains the right shape for any union
                    // exchanged with peers you do not build in lockstep.
                    _ => ::std::result::Result::Err(cyclonedds::DdsError::BadParameter(
                        ::std::format!(
                            "DdsUnion clone_out: discriminator {} is not a declared case of {};                              add a #[dds_default] variant to accept unknown discriminators",
                            __disc,
                            #type_name_str,
                        ),
                    )),
                }
            }

            fn write_to_native<'a>(
                &'a self,
                arena: &'a mut cyclonedds::write_arena::WriteArena,
            ) -> cyclonedds::DdsResult<*const ::std::ffi::c_void> {
                // Compute default sentinel value
                let __disc_default_sentinel: u32 = #default_sentinel;
                let mut __native = #native_name {
                    __disc: 0 as #disc_ty,
                    __value: #native_value_name::default(),
                };
                match self {
                    #(#write_arms)*
                }
                Ok(arena.hold(__native) as *const #native_name as *const ::std::ffi::c_void)
            }
        }
    };

    Ok(expanded)
}

