use proc_macro::TokenStream;
use proc_macro2::TokenStream as TokenStream2;
use quote::{format_ident, quote};
use syn::{
    parse_macro_input, Data, DeriveInput, Expr, ExprLit, Field, Fields, GenericArgument, Lit,
    PathArguments, Type, TypePath,
};

type PrimitiveArrayInfo = (TokenStream2, TokenStream2, Vec<TokenStream2>, u32);
type DirectVecInfo = (TokenStream2, u32, TokenStream2);

#[proc_macro_derive(DdsType, attributes(key, dds_enum, dds_typename, dds_type_metadata))]
pub fn derive_dds_type(input: TokenStream) -> TokenStream {
    let input = parse_macro_input!(input as DeriveInput);
    match derive_impl(&input) {
        Ok(tokens) => tokens.into(),
        Err(err) => err.to_compile_error().into(),
    }
}

/// Optional `#[dds_typename("module::Struct")]` on a `DdsType` struct.
///
/// When present, overrides the default short type name so XTypes matching
/// can use the same qualified name as C++ (`m_typename`) / Python (`typename=`).
fn parse_dds_typename(input: &DeriveInput) -> Option<String> {
    for attr in &input.attrs {
        if attr.path().is_ident("dds_typename") {
            if let Ok(lit) = attr.parse_args::<syn::LitStr>() {
                return Some(lit.value());
            }
        }
    }
    None
}

/// Optional `#[dds_type_metadata(info = "CONST", map = "CONST")]` on a `DdsType` struct.
///
/// Points to `&[u8]` constants holding the XCDR2 TypeInformation and TypeMapping
/// blobs (as generated by the C `idlc`). When present, the topic descriptor
/// carries them (DDS_TOPIC_XTYPES_METADATA) so XTypes type-enforcing peers
/// (Python/C++) match our endpoints.
fn parse_dds_type_metadata(input: &DeriveInput) -> Option<(syn::Ident, syn::Ident)> {
    for attr in &input.attrs {
        if attr.path().is_ident("dds_type_metadata") {
            let mut info = None;
            let mut map = None;
            let _ = attr.parse_nested_meta(|meta| {
                if meta.path.is_ident("info") {
                    let lit: syn::LitStr = meta.value()?.parse()?;
                    info = Some(syn::Ident::new(&lit.value(), lit.span()));
                } else if meta.path.is_ident("map") {
                    let lit: syn::LitStr = meta.value()?.parse()?;
                    map = Some(syn::Ident::new(&lit.value(), lit.span()));
                }
                Ok(())
            });
            if let (Some(i), Some(m)) = (info, map) {
                return Some((i, m));
            }
        }
    }
    None
}

